const dictionaries: Record<Lang, Record<Key, string>> = { en, zh };

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = dictionaries[lang][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** Label for a stage or status id, falling back to the raw id. */
export function label(prefix: "stage" | "status" | "task" | "legend" | "label" | "action" | "issue" | "route", id: string): string {
  const key = `${prefix}.${id}` as Key;
  return key in en ? t(key) : id.replace(/_/g, " ");
}

/** The current URL with the interface language switched (keeps the run hash). */
export function langHref(target: Lang): string {
  const url = new URL(window.location.href);
  if (target === "zh") url.searchParams.set("lang", "zh");
  else url.searchParams.delete("lang");
  return url.toString();
}
